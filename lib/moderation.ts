/** 단어를 우회-내성 정규식으로 변환 */
function toPattern(word: string): RegExp {
  // 입력과 동일하게 NFKC 정규화 (호환 자모 ㅅ → 조합 자모 등 표기 통일)
  const escaped = word
    .normalize("NFKC")
    .split("")
    .map((ch) => ch.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"))
    .join("[\\s\\W_]*");
  return new RegExp(escaped, "i");
}

const BANNED_PATTERNS: RegExp[] = BANNED_WORDS.map(toPattern);

/** 금칙어 포함 여부 */
export function containsBanned(text: string): boolean {
  const normalized = text.normalize("NFKC");
  return BANNED_PATTERNS.some((p) => p.test(normalized));
}

